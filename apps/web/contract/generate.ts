// Writes src/api-schema.ts, the API's types, from the pinned contract (openapi.json here) with
// openapi-typescript. Run it after re-pinning: `pnpm openapi` from the repository root.
// contract.test.ts fails when the file it writes and the pinned contract differ.

import { readFile, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

export const CONTRACT = new URL("openapi.json", import.meta.url);
export const GENERATED = new URL("../src/api-schema.ts", import.meta.url);

const HEADER = `// Generated by \`pnpm openapi\` from apps/web/contract/openapi.json, the API's contract pinned
// from D-E-A-G/qbank-server (see contract/pin.json). Do not edit: re-pin the contract instead.

`;

/** The API's types as the generated file holds them. */
export async function renderTypes(): Promise<string> {
  const ast = await openapiTS(await readFile(CONTRACT, "utf8"));
  return HEADER + astToString(ast);
}

if (import.meta.main) {
  await writeFile(GENERATED, await renderTypes());
  console.log(`Wrote ${GENERATED.pathname}`);
}
